std::shared_ptr<render::Mesh> FluidSurfaceExtractor::BuildMesh(render::rhi::IDevice* device, const FluidSimulation& sim, float isoValue) const {
    const auto& field = sim.GetDensityField();
    if (field.empty()) return std::make_shared<render::Mesh>();

    const auto simDesc = sim.GetDesc();
    const math::IVec3 res = simDesc.resolution;
    const math::Vec3 cellSize = simDesc.volumeSize / math::Vec3(
        static_cast<float>(res.x - 1),
        static_cast<float>(res.y - 1),
        static_cast<float>(res.z - 1));
    const math::Vec3 halfVolume = simDesc.volumeSize * 0.5f;

    render::MeshDescriptor meshDesc;
    meshDesc.vertices.reserve(res.x * res.y * res.z);
    meshDesc.indexFormat = render::IndexFormat::UInt32;
    meshDesc.indices16.clear();

    auto sample = [&](int x, int y, int z) {
        x = std::max(0, std::min(res.x - 1, x));
        y = std::max(0, std::min(res.y - 1, y));
        z = std::max(0, std::min(res.z - 1, z));
        return field[static_cast<size_t>(x + y * res.x + z * res.x * res.y)];
    };

    for (int z = 0; z < res.z - 1; ++z) {
        for (int y = 0; y < res.y - 1; ++y) {
            for (int x = 0; x < res.x - 1; ++x) {
                float cube[8] = {
                    sample(x, y, z),
                    sample(x + 1, y, z),
                    sample(x + 1, y + 1, z),
                    sample(x, y + 1, z),
                    sample(x, y, z + 1),
                    sample(x + 1, y, z + 1),
                    sample(x + 1, y + 1, z + 1),
                    sample(x, y + 1, z + 1)
                };
                int cubeIndex = 0;
                if (cube[0] < isoValue) cubeIndex |= 1;
                if (cube[1] < isoValue) cubeIndex |= 2;
                if (cube[2] < isoValue) cubeIndex |= 4;
                if (cube[3] < isoValue) cubeIndex |= 8;
                if (cube[4] < isoValue) cubeIndex |= 16;
                if (cube[5] < isoValue) cubeIndex |= 32;
                if (cube[6] < isoValue) cubeIndex |= 64;
                if (cube[7] < isoValue) cubeIndex |= 128;

                if (kEdgeTable[cubeIndex] == 0) continue;

                math::Vec3 p[8] = {
                    math::Vec3((x + 0) * cellSize.x, (y + 0) * cellSize.y, (z + 0) * cellSize.z) - halfVolume,
                    math::Vec3((x + 1) * cellSize.x, (y + 0) * cellSize.y, (z + 0) * cellSize.z) - halfVolume,
                    math::Vec3((x + 1) * cellSize.x, (y + 1) * cellSize.y, (z + 0) * cellSize.z) - halfVolume,
                    math::Vec3((x + 0) * cellSize.x, (y + 1) * cellSize.y, (z + 0) * cellSize.z) - halfVolume,
                    math::Vec3((x + 0) * cellSize.x, (y + 0) * cellSize.y, (z + 1) * cellSize.z) - halfVolume,
                    math::Vec3((x + 1) * cellSize.x, (y + 0) * cellSize.y, (z + 1) * cellSize.z) - halfVolume,
                    math::Vec3((x + 1) * cellSize.x, (y + 1) * cellSize.y, (z + 1) * cellSize.z) - halfVolume,
                    math::Vec3((x + 0) * cellSize.x, (y + 1) * cellSize.y, (z + 1) * cellSize.z) - halfVolume
                };
                math::Vec3 vertList[12];
                if (kEdgeTable[cubeIndex] & 1)   vertList[0]  = VertexInterp(isoValue, p[0], p[1], cube[0], cube[1]);
                if (kEdgeTable[cubeIndex] & 2)   vertList[1]  = VertexInterp(isoValue, p[1], p[2], cube[1], cube[2]);
                if (kEdgeTable[cubeIndex] & 4)   vertList[2]  = VertexInterp(isoValue, p[2], p[3], cube[2], cube[3]);
                if (kEdgeTable[cubeIndex] & 8)   vertList[3]  = VertexInterp(isoValue, p[3], p[0], cube[3], cube[0]);
                if (kEdgeTable[cubeIndex] & 16)  vertList[4]  = VertexInterp(isoValue, p[4], p[5], cube[4], cube[5]);
                if (kEdgeTable[cubeIndex] & 32)  vertList[5]  = VertexInterp(isoValue, p[5], p[6], cube[5], cube[6]);
                if (kEdgeTable[cubeIndex] & 64)  vertList[6]  = VertexInterp(isoValue, p[6], p[7], cube[6], cube[7]);
                if (kEdgeTable[cubeIndex] & 128) vertList[7]  = VertexInterp(isoValue, p[7], p[4], cube[7], cube[4]);
                if (kEdgeTable[cubeIndex] & 256) vertList[8]  = VertexInterp(isoValue, p[0], p[4], cube[0], cube[4]);
                if (kEdgeTable[cubeIndex] & 512) vertList[9]  = VertexInterp(isoValue, p[1], p[5], cube[1], cube[5]);
                if (kEdgeTable[cubeIndex] & 1024)vertList[10] = VertexInterp(isoValue, p[2], p[6], cube[2], cube[6]);
                if (kEdgeTable[cubeIndex] & 2048)vertList[11] = VertexInterp(isoValue, p[3], p[7], cube[3], cube[7]);

                for (int i = 0; kTriTable[cubeIndex][i] != -1; i += 3) {
                    for (int k = 0; k < 3; ++k) {
                        const int e = kTriTable[cubeIndex][i + k];
                        const math::Vec3 pos = vertList[e];
                        const math::Vec3 pos01 = math::Vec3(
                            pos.x / std::max(0.0001f, simDesc.volumeSize.x) + 0.5f,
                            pos.y / std::max(0.0001f, simDesc.volumeSize.y) + 0.5f,
                            pos.z / std::max(0.0001f, simDesc.volumeSize.z) + 0.5f);
                        render::Vertex v{};
                        v.position = pos;
                        v.normal = GradientAt(field, res, pos01);
                        v.uv = math::Vec2(0, 0);
                        meshDesc.vertices.push_back(v);
                        meshDesc.indices32.push_back(static_cast<uint32_t>(meshDesc.indices32.size()));
                    }
                }
            }
        }
    }

    meshDesc.submeshes.clear();
    if (!device || meshDesc.vertices.empty()) return std::make_shared<render::Mesh>();
    return render::Mesh::Create(device, meshDesc);
}

